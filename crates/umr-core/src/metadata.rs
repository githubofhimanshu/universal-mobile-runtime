use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

/// Supported mobile package formats.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum PackageFormat {
    Apk,
    Ipa,
    Unknown,
}

impl std::fmt::Display for PackageFormat {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Apk => write!(f, "apk"),
            Self::Ipa => write!(f, "ipa"),
            Self::Unknown => write!(f, "unknown"),
        }
    }
}

/// Target ABI for Android native libraries.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TargetAbi {
    #[serde(rename = "arm64-v8a")]
    Arm64V8a,
    #[serde(rename = "armeabi-v7a")]
    ArmeabiV7a,
    #[serde(rename = "x86_64")]
    X86_64,
    #[serde(rename = "x86")]
    X86,
    #[serde(rename = "unknown")]
    Unknown,
}

impl TargetAbi {
    pub fn from_lib_folder_name(name: &str) -> Self {
        match name {
            "arm64-v8a" => Self::Arm64V8a,
            "armeabi-v7a" => Self::ArmeabiV7a,
            "x86_64" => Self::X86_64,
            "x86" => Self::X86,
            _ => Self::Unknown,
        }
    }
}

/// CPU architecture for iOS Mach-O executables.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CpuArchitecture {
    #[serde(rename = "arm64")]
    Arm64,
    #[serde(rename = "armv7")]
    Armv7,
    #[serde(rename = "x86_64")]
    X86_64,
    #[serde(rename = "universal")]
    Universal,
    #[serde(rename = "unknown")]
    Unknown,
}

/// Binary encryption / DRM status (primarily for iOS FairPlay).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum EncryptionStatus {
    Unencrypted,
    FairPlayEncrypted { cryptid: u32 },
    Unknown,
}

/// Extracted Android-specific application metadata.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AndroidPackageInfo {
    pub package_name: String,
    pub version_code: Option<u64>,
    pub version_name: Option<String>,
    pub min_sdk_version: Option<u32>,
    pub target_sdk_version: Option<u32>,
    pub main_activity: Option<String>,
    pub native_abis: Vec<TargetAbi>,
    pub is_pure_dex: bool,
}

/// Extracted iOS-specific application metadata.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct IosPackageInfo {
    pub bundle_identifier: String,
    pub bundle_version: Option<String>,
    pub bundle_short_version: Option<String>,
    pub minimum_os_version: Option<String>,
    pub architectures: Vec<CpuArchitecture>,
    pub encryption: EncryptionStatus,
    pub is_simulator_build: bool,
}

/// Variant holding platform-specific package details.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "platform", rename_all = "snake_case")]
pub enum PackageDetails {
    Android(AndroidPackageInfo),
    Ios(IosPackageInfo),
}

/// Canonical, immutable package metadata record generated by the isolated intake worker.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PackageMetadata {
    pub format: PackageFormat,
    pub file_path: String,
    pub file_size_bytes: u64,
    pub sha256_hash: String,
    pub details: PackageDetails,
    pub inspected_at: DateTime<Utc>,
}

impl PackageMetadata {
    pub fn package_id(&self) -> &str {
        match &self.details {
            PackageDetails::Android(info) => &info.package_name,
            PackageDetails::Ios(info) => &info.bundle_identifier,
        }
    }

    pub fn is_ios_encrypted(&self) -> bool {
        match &self.details {
            PackageDetails::Ios(info) => matches!(info.encryption, EncryptionStatus::FairPlayEncrypted { .. }),
            _ => false,
        }
    }
}

